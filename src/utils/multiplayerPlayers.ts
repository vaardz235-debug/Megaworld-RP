export function updateSimulatedPlayers(players: WorldPlayer[]): WorldPlayer[] {
  return players.map(player => {
    // 35% chance to wander slightly left or right
    let newX = player.x;
    let isWalking = player.isWalking;
    let facing = player.facing;

    if (Math.random() < 0.35) {
      const step = Math.random() < 0.5 ? -1 : 1;
      const proposedX = Math.max(1, Math.min(88, newX + step));
      if (proposedX !== newX) {
        newX = proposedX;
        isWalking = true;
        facing = step > 0 ? 'right' : 'left';
      }
    } else if (Math.random() < 0.25) {
      isWalking = false;
    }

    // 15% chance to update speech message
    let speechText = player.speechText;
    let speechTimer = player.speechTimer || 0;

    if (speechTimer > 0) {
      speechTimer--;
      if (speechTimer <= 0) {
        speechText = undefined;
      }
    } else if (Math.random() < 0.08) {
      speechText = AMBIENT_PLAYER_CHATS[Math.floor(Math.random() * AMBIENT_PLAYER_CHATS.length)];
      speechTimer = 5; // stays for 5 cycles
    }

    return {
      ...player,
      x: newX,
      isWalking,
      facing,
      speechText,
      speechTimer,
    };
  });
}
